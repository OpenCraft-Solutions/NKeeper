// The modules shared through the import map (docs/plugin-security.md §7.2): specifier -> entry name.
export const SHARED = {
  react: 'react',
  'react/jsx-runtime': 'react-jsx-runtime',
  'react-dom': 'react-dom',
  'react-dom/client': 'react-dom-client',
  '@nkeeper/sdk': 'nkeeper-sdk',
}

/** Packages published as CommonJS, whose named exports must be listed explicitly to re-export them. */
export const COMMONJS = ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client']

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/

/** An ES module that re-exports a CommonJS module's default and every named export. */
export function reexport(specifier, names) {
  const named = [...new Set(names)].filter((n) => n !== 'default' && n !== '__esModule' && IDENTIFIER.test(n)).sort()
  return [
    `// Generated by scripts/generate.mjs: re-exports ${specifier} as one shared ES module.`,
    `import shared from '${specifier}'`,
    'export default shared',
    named.length ? `export const { ${named.join(', ')} } = shared` : '',
    '',
  ].join('\n')
}

/** The import map for built entry files: `{ imports: { specifier: url } }`, keys sorted. */
export function importMap(fileBySpecifier, base = '/') {
  const imports = {}
  for (const specifier of Object.keys(fileBySpecifier).sort()) {
    imports[specifier] = base + fileBySpecifier[specifier]
  }
  return { imports }
}
