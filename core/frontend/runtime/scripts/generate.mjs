// Writes src/generated/<entry>.js for each shared module (see shared.mjs). Run before `vite build`.
import { mkdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { COMMONJS, SHARED, reexport } from './shared.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src', 'generated')
const require = createRequire(join(root, 'package.json'))
mkdirSync(out, { recursive: true })

for (const [specifier, entry] of Object.entries(SHARED)) {
  const source = COMMONJS.includes(specifier)
    ? reexport(specifier, Object.keys(require(specifier)))
    : `// Generated by scripts/generate.mjs: the shared ${specifier}.\nexport * from '${specifier}'\n`
  writeFileSync(join(out, `${entry}.js`), source)
}
console.log(`Generated ${Object.keys(SHARED).length} shared modules in ${out}`)
